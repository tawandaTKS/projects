// Generates the vendor Ed25519 key pair for licence keys.
//   npm run license:keygen            → creates tools/license/.keys/private.key and embeds the public key
//   npm run license:keygen -- --force → replaces an existing pair (invalidates every issued key!)
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { generateKeyPair } from '../../packages/core/src/license.ts';

const dir = new URL('./.keys/', import.meta.url);
const privPath = new URL('private.key', dir);
if (existsSync(privPath) && !process.argv.includes('--force')) {
  console.error('A private key already exists at tools/license/.keys/private.key. Use --force to replace it (all issued keys stop working).');
  process.exit(1);
}
const { privateKeyHex, publicKeyHex } = generateKeyPair();
mkdirSync(dir, { recursive: true, mode: 0o700 });
writeFileSync(privPath, privateKeyHex + '\n', { mode: 0o600 });
const keyFile = new URL('../../packages/core/src/licenseKey.ts', import.meta.url);
writeFileSync(
  keyFile,
  `/**
 * Ed25519 public key used to verify licence keys. Generated by \`npm run license:keygen\`.
 * An empty key means "developer build": licensing is bypassed and a banner is shown.
 */
export const LICENSE_PUBLIC_KEY_HEX = '${publicKeyHex}';
`,
);
console.log('Public key embedded in packages/core/src/licenseKey.ts');
console.log('Private key written to tools/license/.keys/private.key — back it up somewhere safe and NEVER commit it.');
